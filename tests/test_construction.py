def assert_validation_source(error: ValidationError, source: Path, detail: str) -> None:
    relative = source.resolve().relative_to(REPO_ROOT.resolve(), walk_up=True)
    assert str(error) == f"{relative}: {detail}"
    assert (REPO_ROOT / relative).resolve() == source.resolve()

